"""Generate a Blender script that builds the IDPS venue inside Blender.

Run it once in Blender (Scripting tab -> Open -> Run Script) before designing a show with
Skybrush Studio. It creates an "IDPS venue" collection, in the same axes the show importer
uses (Blender +X = East, +Y = North, +Z = up, origin = the calibration square):

* the performance area as a wireframe box (drones must stay inside it);
* the region where coverage is proven (the planner's inset from walls and ceiling);
* the origin with North / East arrows;
* trusses, and every planned camera with its view direction.

Everything is locked and hidden from renders, so it only guides the design.
"""
from __future__ import annotations

import json

import numpy as np

from idps.show.placement import Placement


def venue_geometry(site, cameras=None, placement: Placement | None = None) -> dict:
    """Venue elements in show (Blender) axes, as plain lists (JSON-able)."""
    pl = placement or Placement()
    f = site.frame
    vol = site.volume

    def to_show(xyz):
        return pl.from_ned(f.ned(np.atleast_2d(np.asarray(xyz, float)))).round(4).tolist()

    poly = np.asarray(vol.polygon, float)
    floor = to_show(np.column_stack([poly, np.full(len(poly), vol.z_min)]))
    top = to_show(np.column_stack([poly, np.full(len(poly), vol.z_max)]))
    from idps.coverage.volume import offset_ring
    inset = site.eval_inset_m
    inner = offset_ring(poly, -inset, 1e9)
    inner = inner[1::2] if len(inner) == 2 * len(poly) else inner
    z0, z1 = max(vol.z_min, 0.2), vol.z_max - inset
    proven = [to_show(np.column_stack([inner, np.full(len(inner), z)])) for z in (z0, z1)]
    o = to_show([[*f.origin_xy, 0.0]])[0]
    n_tip = to_show([[*(np.asarray(f.origin_xy) + f.n_hat * 1.5), 0.0]])[0]
    e_tip = to_show([[*(np.asarray(f.origin_xy) + f.e_hat * 1.0), 0.0]])[0]
    trusses = [{"id": t.id, "a": to_show([[*t.start, t.height_m]])[0], "b": to_show([[*t.end, t.height_m]])[0]}
               for t in site.trusses]
    cams = []
    for c in cameras or []:
        p = np.asarray(c.position_m, float)
        tip = p + np.asarray(c.R[2]) * 1.5
        cams.append({"id": c.id, "pos": to_show([p])[0], "tip": to_show([tip])[0]})
    return {"name": site.name, "floor": floor, "top": top, "proven": proven, "origin": o, "north": n_tip,
            "east": e_tip, "trusses": trusses, "cameras": cams}


SCRIPT = r'''# IDPS venue for Blender: generated by `idps-show blender-venue`. Run once before designing.
# Axes: Blender +X = East, +Y = North, +Z = up; origin = the calibration square corner.
import bpy

V = json.loads(VENUE)
coll = bpy.data.collections.get("IDPS venue") or bpy.data.collections.new("IDPS venue")
if coll.name not in bpy.context.scene.collection.children:
    bpy.context.scene.collection.children.link(coll)
for ob in list(coll.objects):
    bpy.data.objects.remove(ob, do_unlink=True)


def add(name, verts, edges=(), faces=(), colour=(1, 1, 1, 1)):
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(v) for v in verts], list(edges), list(faces))
    ob = bpy.data.objects.new(name, me)
    ob.display_type = "WIRE"
    ob.color = colour
    ob.hide_render = True
    ob.hide_select = True
    coll.objects.link(ob)
    return ob


def prism(name, bottom, top, colour):
    n = len(bottom)
    edges = [(i, (i + 1) % n) for i in range(n)] + [(n + i, n + (i + 1) % n) for i in range(n)] + \
            [(i, n + i) for i in range(n)]
    return add(name, bottom + top, edges, (), colour)


prism("Performance area", V["floor"], V["top"], (0.16, 0.47, 0.84, 1))
prism("Proven coverage", V["proven"][0], V["proven"][1], (0.05, 0.64, 0.05, 1))
o = V["origin"]
add("Origin N (north)", [o, V["north"]], [(0, 1)], (), (0.82, 0.23, 0.23, 1))
add("Origin E (east)", [o, V["east"]], [(0, 1)], (), (0.16, 0.47, 0.84, 1))
for name, at in (("N", V["north"]), ("E", V["east"])):
    cu = bpy.data.curves.new(f"IDPS {name}", "FONT")
    cu.body = name
    cu.size = 0.4
    ob = bpy.data.objects.new(f"IDPS label {name}", cu)
    ob.location = at
    ob.hide_render = True
    coll.objects.link(ob)
for t in V["trusses"]:
    add(f"Truss {t['id']}", [t["a"], t["b"]], [(0, 1)], (), (0.42, 0.42, 0.4, 1))
for c in V["cameras"]:
    add(f"Camera {c['id']}", [c["pos"], c["tip"]], [(0, 1)], (), (0.92, 0.41, 0.2, 1))
bpy.context.scene.unit_settings.system = "METRIC"
print(f"IDPS venue '{V['name']}': {len(V['cameras'])} cameras, {len(V['trusses'])} trusses")
'''


def blender_script(site, cameras=None, placement: Placement | None = None) -> str:
    geo = venue_geometry(site, cameras, placement)
    return "import json\nVENUE = " + repr(json.dumps(geo)) + "\n" + SCRIPT
